/**
 * One-off: convert the 2025 production export (a D1 SQL dump) into restorable contest backups,
 * compare the new rankings with the old app's stored results, and optionally upload to the NEW deployment.
 *
 *   bun scripts/migrate-2025.ts --dump <werewolf-d1.sql> [--out dir] [--report file]
 *                               [--target https://werewolf-v2.example --password-env ORGANIZER_PASSWORD]
 *
 * Uploading restores each contest under its 2025 identifier, so running it again replaces the same
 * contest and never creates a copy. The old application is never contacted.
 */
import { Database } from 'bun:sqlite'
import { individualRankings, replay } from '@werewolf/core'
import { Snapshot } from '@werewolf/sync'
import * as Option from 'effect/Option'
import * as Result from 'effect/Result'
import * as Schema from 'effect/Schema'
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { convertContest, SourceData } from './migration/convert.ts'

const arg = (name: string) => {
  const index = process.argv.indexOf('--' + name)
  return index >= 0 ? (process.argv[index + 1] ?? '') : ''
}
const dump =
  arg('dump') ||
  (process.env['HOME'] ?? '') + '/backups/werewolf/prod-20261007-1747/werewolf-d1.sql'
const out = arg('out') || '/tmp/werewolf-migration'
const reportPath = arg('report')
const target = arg('target')

const db = new Database(':memory:')
db.exec(readFileSync(dump, 'utf8'))
const rows = (sql: string, ...params: Array<string>): ReadonlyArray<unknown> =>
  db.query(sql).all(...params)
const parse = <A, I>(schema: Schema.Codec<A, I>, input: unknown): A =>
  Schema.decodeUnknownSync(schema)(input)
const OldResult = Schema.Struct({
  registration_id: Schema.String,
  coefficient_points: Schema.Number,
  place_open: Schema.OptionFromNullOr(Schema.Number),
  place_in_age_class: Schema.OptionFromNullOr(Schema.Number),
  place_in_weight_class: Schema.OptionFromNullOr(Schema.Number),
})
const contests = parse(
  Schema.Array(SourceData.fields.contest),
  rows('select * from contests order by date'),
)
mkdirSync(out, { recursive: true })
const report: Array<string> = [
  '# 2025 migration report',
  '',
  'Generated by `scripts/migrate-2025.ts` from the production export of 2026-10-07. Lifters are identified by their lot number in the migrated contest, not by name.',
]
for (const contest of contests) {
  const inContest = '(select id from registrations where contest_id = ?)'
  const source = parse(SourceData, {
    contest,
    tags: rows('select label, created_at from contest_tags where contest_id = ?', contest.id),
    ageCategories: rows(
      'select code, name, min_age, max_age, sort_order from contest_age_categories where contest_id = ?',
      contest.id,
    ),
    weightClasses: rows(
      'select gender, code, name, max_weight, sort_order from contest_weight_classes where contest_id = ?',
      contest.id,
    ),
    plates: rows('select plate_weight, quantity from plate_sets where contest_id = ?', contest.id),
    registrations: rows(
      `select r.id, r.competitor_id, r.bodyweight, r.rack_height_bench, r.flight_order, r.created_at, r.labels,
              c.first_name, c.last_name, c.birth_date, c.gender, c.club
         from registrations r join competitors c on c.id = r.competitor_id where r.contest_id = ?`,
      contest.id,
    ),
    lifts: rows(
      'select registration_id, lift_type from registration_lifts where registration_id in ' +
        inContest,
      contest.id,
    ),
    attempts: rows(
      'select id, registration_id, lift_type, attempt_number, weight, status, timestamp, created_at from attempts where registration_id in ' +
        inContest,
      contest.id,
    ),
  })
  const conversion = convertContest(source)
  const backup = Schema.decodeUnknownSync(Snapshot)(conversion.backup)
  writeFileSync(out + '/' + contest.id + '.json', JSON.stringify(conversion.backup))
  const state = Result.getOrThrow(
    replay(
      backup.definition.rulebook,
      backup.definition.date,
      backup.commands.map((item) => item.command),
    ),
  )
  const old = parse(
    Schema.Array(OldResult),
    rows(
      'select registration_id, coefficient_points, place_open, place_in_age_class, place_in_weight_class from results where contest_id = ?',
      contest.id,
    ),
  )
  const rankings = individualRankings(state)
  const lot = (id: string) => state.entries.find((entry) => entry.id === id)?.lotNumber ?? 0
  const placeIn = (classification: string, id: string) => {
    const ranking = rankings.find((item) => item.classificationId === classification)
    for (const group of ranking?.groups ?? []) {
      const row = group.rows.find((item) => item.entry.id === id)
      if (row) return Option.some({ place: row.place, points: row.points })
    }
    return Option.none<{ place: number; points: number }>()
  }
  const text = (place: Option.Option<number>) =>
    Option.match(place, { onNone: () => 'not ranked', onSome: String })
  // Places start at 1, so -1 safely stands for "no place" when comparing.
  const same = (left: Option.Option<number>, right: Option.Option<number>) =>
    Option.getOrElse(left, () => -1) === Option.getOrElse(right, () => -1)
  type Kind = 'noResult' | 'tie' | 'other'
  const differences: Array<{ kind: Kind; line: string }> = []
  const compared = { open: 0, age: 0, weight: 0 }
  const tiedWith = (id: string) =>
    old.some(
      (other) =>
        other.registration_id !== id &&
        Math.abs(
          other.coefficient_points -
            (old.find((item) => item.registration_id === id)?.coefficient_points ?? -1),
        ) < 0.0005 &&
        other.coefficient_points > 0,
    )
  for (const result of old) {
    const number = lot(result.registration_id)
    const open = placeIn('open', result.registration_id)
    const points = Option.match(open, { onNone: () => 0, onSome: (item) => item.points })
    const pointsAgree = Math.abs(points - result.coefficient_points) < 0.01
    const kindOf = (now: Option.Option<number>): Kind =>
      Option.isNone(now) && result.coefficient_points === 0
        ? 'noResult'
        : pointsAgree && tiedWith(result.registration_id)
          ? 'tie'
          : 'other'
    const check = (label: string, before: Option.Option<number>, now: Option.Option<number>) => {
      if (Option.isNone(before) && Option.isNone(now)) return
      if (label === 'Open') compared.open++
      if (label === 'age class') compared.age++
      if (label === 'weight class') compared.weight++
      if (!same(before, now) || (label === 'Open' && !pointsAgree))
        differences.push({
          kind: kindOf(now),
          line:
            'lot ' +
            number +
            ': ' +
            label +
            ' place ' +
            text(before) +
            ' before, ' +
            text(now) +
            ' now' +
            (label === 'Open'
              ? ' (points ' +
                result.coefficient_points.toFixed(3) +
                ' before, ' +
                points.toFixed(3) +
                ' now)'
              : ''),
        })
    }
    check(
      'Open',
      result.place_open,
      Option.map(open, (item) => item.place),
    )
    check(
      'age class',
      result.place_in_age_class,
      Option.map(placeIn('open-age', result.registration_id), (item) => item.place),
    )
    check(
      'weight class',
      result.place_in_weight_class,
      Option.map(placeIn('open-weight', result.registration_id), (item) => item.place),
    )
  }
  const count = (kind: Kind) => differences.filter((item) => item.kind === kind).length
  report.push(
    '',
    '## ' + backup.definition.name + ' (' + backup.definition.date + ')',
    '',
    '- Entries: ' +
      state.entries.length +
      '; attempts with a weight: ' +
      state.attempts.filter((a) => a._tag !== 'Unannounced').length +
      ' of ' +
      state.attempts.length +
      ' slots; commands: ' +
      backup.commands.length,
    '- Divisions: ' + conversion.divisions.map((item) => item.label).join(', '),
    '- Did not start (DNS): ' +
      conversion.didNotStart +
      ' entry-lift pairs (all attempts were 20 kg and failed in 2025).',
    ...conversion.adjustments.map((line) => '- Adjustment: ' + line),
    '- Stored old results: ' +
      old.length +
      ' rows. Compared: Open ' +
      compared.open +
      ', age class ' +
      compared.age +
      ', weight class ' +
      compared.weight +
      '.',
    '- Differences: ' +
      differences.length +
      ' (no good lift: ' +
      count('noResult') +
      ', tie-break: ' +
      count('tie') +
      ', unexplained: ' +
      count('other') +
      ')',
    '  - "no good lift": the old app gave places to lifters with 0 points, including lifters who did not start (DNS); the new app ranks only lifters with a good lift and shows DNS.',
    '  - "tie-break": equal points; the new order is bodyweight (lighter first), then who reached the result first.',
    ...differences
      .filter((item) => item.kind === 'other')
      .map((item) => '  - UNEXPLAINED ' + item.line),
    ...differences.filter((item) => item.kind === 'tie').map((item) => '  - tie ' + item.line),
  )
  if (target) {
    const base = new URL(target)
    if (!/werewolf-v2|^localhost$|^127\./.test(base.hostname))
      throw new Error(
        'Refusing to upload to ' + base.hostname + ': it does not look like the new deployment.',
      )
    const headers = { 'Content-Type': 'application/json', Origin: base.origin }
    const login = await fetch(base.origin + '/api/session', {
      method: 'POST',
      headers,
      body: JSON.stringify({
        password: process.env[arg('password-env') || 'ORGANIZER_PASSWORD'] ?? '',
      }),
    })
    const cookie = (login.headers.get('Set-Cookie') ?? '').split(';')[0] ?? ''
    const response = await fetch(base.origin + '/api/contests/' + contest.id + '/restore', {
      method: 'POST',
      headers: { ...headers, Cookie: cookie },
      body: JSON.stringify(conversion.backup),
    })
    report.push('- Upload to ' + base.hostname + ': HTTP ' + response.status)
    if (!response.ok) throw new Error('Upload of ' + contest.id + ' failed with ' + response.status)
  }
}
const finished = report.join('\n') + '\n'
if (reportPath) writeFileSync(reportPath, finished)
else console.log(finished)
