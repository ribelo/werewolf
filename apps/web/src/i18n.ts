export function rejectionText(reason: string, locale: keyof typeof catalogs): string {
  return rejectionMessages[reason]?.[locale] ?? reason
}
export type MessageKey = keyof typeof catalogs.pl
type Locale = keyof typeof catalogs
const localeAtom = Atom.make<Locale>('pl')

export function useMessages() {
  const [locale, setLocale] = useAtom(localeAtom)
  const dictionary = new Map<string, string>(Object.entries(catalogs[locale]))
  return {
    locale,
    setLocale,
    t: (key: MessageKey): string => catalogs[locale][key],
    /** For keys built at run time from a code such as a problem or warning name. */
    tx: (key: string): string => dictionary.get(key) ?? key,
  }
}
